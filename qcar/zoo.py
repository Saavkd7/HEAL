"""QCar model zoo: train every HEAL fusion method on QCar and keep one clean,
loadable checkpoint folder per method. Everything it does is defined in
qcar/zoo.json; this file hardcodes no method, path or checkpoint.

    python qcar/zoo.py configs            # write qcar/configs/zoo/<method>.yaml
    python qcar/zoo.py check [m ...]      # build + init + a few AMP train steps each (catches OOM / key errors)
    python qcar/zoo.py train [m ...]      # sequential queue: train -> eval -> collect; skips finished methods
    python qcar/zoo.py collect <m> <run>  # copy one finished run into the zoo by hand
    python qcar/zoo.py index              # rewrite <checkpoints_dir>/INDEX.md from the collected evals

A collected method folder is directly loadable:
    python qcar/eval.py --model_dir checkpoints/qcar/zoo/<method>
"""
import argparse
import copy
import glob
import json
import os
import re
import shutil
import subprocess
import sys
import time

import yaml

from qcar import config

ZOO_JSON = os.path.join(config.HERE, "zoo.json")
KEEP_FILES = ("config.yaml", "resolved_hypes.json", "run_log.json", "eval_validate.json")


def load_zoo():
    return config.load_conf(ZOO_JSON)


def selected(zoo, names):
    names = names or list(zoo["methods"])
    unknown = [n for n in names if n not in zoo["methods"]]
    if unknown:
        raise SystemExit("unknown method(s) %s; zoo.json defines %s" %
                         (unknown, list(zoo["methods"])))
    return names


def config_path(zoo, name):
    return os.path.join(zoo.path_of("configs_dir"), name + ".yaml")


def read_yaml(path, text_fixes=None):
    with open(config.repo_path(path)) as f:
        text = f.read()
    for old, new in (text_fixes or {}).items():
        if old not in text:
            raise SystemExit("source_text_fixes: %r not found in %s" % (old[:40], path))
        text = text.replace(old, new)
    return yaml.load(text, Loader=yaml.Loader)


def get_by_path(hypes, dotted_key):
    node = hypes
    for part in dotted_key.split("."):
        node = node[part]
    return node


