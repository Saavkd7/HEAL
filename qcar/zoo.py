def cmd_check(zoo, names):
    """Same code path as train.py (plugins, registry, weight init, freeze),
    then check_steps AMP forward/backward steps, reporting peak GPU memory."""
    import torch
    from torch.utils.data import DataLoader
    import opencood.hypes_yaml.yaml_utils as yaml_utils
    from opencood.data_utils.datasets import build_dataset
    from opencood.tools import train_utils
    from qcar import registry, train as qtrain

    conf = config.load_conf()
    no_cli = argparse.Namespace(plugins=None, model_packages=None, loss_packages=None)
    results = {}
    dataset = dataset_key = None
    for name in selected(zoo, names):
        print("\n==== check %s ====" % name)
        torch.cuda.empty_cache()
        torch.cuda.reset_peak_memory_stats()
        try:
            hypes = yaml_utils.load_yaml(config_path(zoo, name), None)
            config.resolve_modules(no_cli, hypes, conf)
            # labels depend on postprocess (anchor feature_stride), so only
            # reuse the dataset between methods whose data sections match
            data_key = json.dumps([hypes["postprocess"], hypes["preprocess"],
                                   hypes["heter"]], sort_keys=True, default=str)
            if dataset is None or data_key != dataset_key:
                dataset = build_dataset(hypes, visualize=False, train=True)
                dataset_key = data_key
            loader = DataLoader(dataset, batch_size=conf["train_batch_size"], shuffle=True,
                                num_workers=0, collate_fn=dataset.collate_batch_train)
            model = registry.create_model(hypes)
            qtrain.load_initial_weights(hypes, model, len(dataset))
            criterion = registry.create_loss(hypes)
            optimizer = train_utils.setup_optimizer(hypes, model)
            model.cuda().train()
            use_amp = "--no_amp" not in zoo["methods"][name].get("train_flags", [])
            scaler = torch.cuda.amp.GradScaler(enabled=use_amp)
            started = time.time()
            steps = 0
            for batch in loader:
                batch = train_utils.to_device(batch, torch.device("cuda"))
                batch["ego"]["epoch"] = 0
                with torch.cuda.amp.autocast(enabled=use_amp):
                    out = model(batch["ego"])
                    loss = criterion(out, batch["ego"]["label_dict"])
                    if hypes["model"]["args"].get("supervise_single", False):
                        loss = loss + criterion(out, batch["ego"]["label_dict_single"],
                                                suffix="_single")
                scaler.scale(loss).backward()
                scaler.step(optimizer); scaler.update(); optimizer.zero_grad()
                steps += 1
                if steps >= zoo["check_steps"]:
                    break
            peak = torch.cuda.max_memory_allocated() / 2 ** 30
            results[name] = "OK   loss %.3f  peak %.2f GiB  %.2fs/step" % (
                loss.item(), peak, (time.time() - started) / steps)
        except Exception as err:  # report and continue with the next method
            results[name] = "FAIL %s: %s" % (type(err).__name__, str(err).splitlines()[0][:150])
        finally:
            model = optimizer = criterion = out = loss = scaler = None
            torch.cuda.empty_cache()
        print(results[name])
    print("\n==== summary ====")
    for name, line in results.items():
        print("%-11s %s" % (name, line))
    return results


