# configs
# --------------------------------------------------------------------------

def build_config(zoo, name):
    method = zoo["methods"][name]
    sensor = method["sensor"]
    if sensor not in zoo["bases"]:
        raise SystemExit("%s: no bases.%s in zoo.json" % (name, sensor))
    base = read_yaml(zoo["bases"][sensor])
    source = read_yaml(method["model_from"], method.get("source_text_fixes"))

    cfg = copy.deepcopy(base)
    cfg["name"] = "QCarZoo_%s" % name
    cfg["model"] = copy.deepcopy(source["model"])
    cfg["model"]["args"].update(method.get("model_args", {}))
    if method.get("loss_from_source"):
        cfg["loss"] = copy.deepcopy(source["loss"])
    for key in method.get("keys_from_source", []):
        config.set_by_path(cfg, key, copy.deepcopy(get_by_path(source, key)))
    if method.get("extra_plugins"):
        cfg["_qcar_plugins"] = (config.split_list(config.load_conf()["plugins"])
                                + list(method["extra_plugins"]))

    if sensor == "camera":
        # QCar camera: 1 front camera, 480x640, no depth ground truth
        ego = cfg["heter"]["ego_modality"]
        base_encoder = base["model"]["args"][ego]["encoder_args"]
        encoder = cfg["model"]["args"][ego]["encoder_args"]
        encoder["data_aug_conf"] = copy.deepcopy(base_encoder["data_aug_conf"])
        encoder["depth_supervision"] = base_encoder["depth_supervision"]
    for key, value in method.get("set", {}).items():
        config.set_by_path(cfg, key, copy.deepcopy(value))

    for key in ("_qcar_pretrained_checkpoint",
                "_qcar_encoder_initialization_checkpoint",
                "_qcar_encoder_initialization_prefixes"):
        cfg.pop(key, None)
    if method["init"] == "full":
        cfg["_qcar_pretrained_checkpoint"] = method["pretrained"]
    elif method["init"] == "encoder":
        cfg["_qcar_pretrained_checkpoint"] = None
        cfg["_qcar_encoder_initialization_checkpoint"] = zoo["encoder_init_checkpoint"][sensor]
        cfg["_qcar_encoder_initialization_prefixes"] = list(zoo["encoder_init_prefixes"])
    else:
        raise SystemExit("%s: init must be 'full' or 'encoder'" % name)
    cfg["_qcar_stage"] = "QCar model zoo: %s (%s), generated by qcar/zoo.py from %s + %s" % (
        name, sensor, zoo["bases"][sensor], method["model_from"])
    return cfg


def cmd_configs(zoo, names):
    os.makedirs(zoo.path_of("configs_dir"), exist_ok=True)
    for name in selected(zoo, names):
        cfg = build_config(zoo, name)
        path = config_path(zoo, name)
        with open(path, "w") as f:
            f.write("# GENERATED by qcar/zoo.py configs -- edit qcar/zoo.json, not this file.\n")
            yaml.safe_dump(cfg, f, sort_keys=False, default_flow_style=None)
        print("wrote", os.path.relpath(path, config.REPO_ROOT))


