def method_dir(zoo, name):
    return os.path.join(zoo.path_of("checkpoints_dir"), name)


def is_done(zoo, name):
    d = method_dir(zoo, name)
    return (bool(glob.glob(os.path.join(d, "net_epoch_bestval_at*.pth")))
            and os.path.isfile(os.path.join(d, "eval_validate.json")))


def run_logged(cmd, log_path):
    print("$", " ".join(cmd), ">", os.path.relpath(log_path, config.REPO_ROOT))
    with open(log_path, "a") as log:
        log.write("\n$ %s\n" % " ".join(cmd))
        log.flush()
        return subprocess.call(cmd, stdout=log, stderr=subprocess.STDOUT,
                               cwd=config.REPO_ROOT)


def run_dir_from_log(log_path):
    with open(log_path) as f:
        found = re.findall(r"run_log\.json in: (.+)", f.read())
    return found[-1].strip() if found else None


def cmd_collect(zoo, name, run_dir):
    run_dir = os.path.abspath(run_dir)
    best = sorted(glob.glob(os.path.join(run_dir, "net_epoch_bestval_at*.pth")))
    if not best:
        raise SystemExit("%s: no net_epoch_bestval_at*.pth in %s" % (name, run_dir))
    dest = method_dir(zoo, name)
    os.makedirs(dest, exist_ok=True)
    for old in glob.glob(os.path.join(dest, "net_epoch_bestval_at*.pth")):
        os.remove(old)
    shutil.copy2(best[-1], dest)
    for fname in KEEP_FILES:
        src = os.path.join(run_dir, fname)
        if os.path.isfile(src):
            shutil.copy2(src, dest)
    with open(os.path.join(dest, "SOURCE_RUN.txt"), "w") as f:
        f.write("trained run: %s\nconfig: %s\n" % (
            os.path.relpath(run_dir, config.REPO_ROOT),
            os.path.relpath(config_path(zoo, name), config.REPO_ROOT)))
    print("collected %s -> %s" % (name, os.path.relpath(dest, config.REPO_ROOT)))


def cmd_index(zoo):
    rows = []
    iou = config.load_conf()["eval_iou_thresh"]
    for name, method in zoo["methods"].items():
        d = method_dir(zoo, name)
        ev_path = os.path.join(d, "eval_validate.json")
        if not os.path.isfile(ev_path):
            rows.append("| %s | %s | %s | - | - | - | not trained yet |" % (
                name, method["sensor"], method["init"]))
            continue
        ev = json.load(open(ev_path))
        iou = ev["iou_thresh"]
        best = sorted(glob.glob(os.path.join(d, "net_epoch_bestval_at*.pth")))
        rows.append("| %s | %s | %s | %.4f | %.4f | %d / %d | `%s` |" % (
            name, method["sensor"], method["init"], ev["average_precision"], ev["recall_at_iou"],
            ev["true_positives"], ev["false_positives"],
            os.path.basename(best[-1]) if best else "?"))
    text = "\n".join([
        "# QCar model zoo",
        "",
        "Generated by `python qcar/zoo.py index` from each method's `eval_validate.json`.",
        "Same data and training recipe for every method (`%s`), validate split, IoU %s." % (
            ", ".join(zoo["bases"].values()), iou),
        "Development numbers only: CoopFront has no independent test trajectory.",
        "",
        "Load any of them: `python qcar/eval.py --model_dir checkpoints/qcar/zoo/<method>`",
        "",
        "| method | sensor | init | AP | recall | TP / FP | checkpoint |",
        "|---|---|---|---|---|---|---|",
    ] + rows) + "\n"
    path = os.path.join(zoo.path_of("checkpoints_dir"), "INDEX.md")
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w") as f:
        f.write(text)
    print(text)


def cmd_train(zoo, names):
    logs = zoo.path_of("logs_dir")
    os.makedirs(logs, exist_ok=True)
    py = sys.executable
    for name in selected(zoo, names):
        if is_done(zoo, name):
            print("skip %s (already in the zoo)" % name)
            continue
        log_path = os.path.join(logs, name + ".log")
        started = time.time()
        code = run_logged([py, "qcar/train.py", "-y", config_path(zoo, name)]
                          + list(zoo["methods"][name].get("train_flags", [])), log_path)
        run_dir = run_dir_from_log(log_path)
        if code != 0 or not run_dir:
            print("FAILED %s (exit %s) -- see %s; continuing" % (name, code, log_path))
            continue
        code = run_logged([py, "qcar/eval.py", "--model_dir", run_dir,
                           "--split", "validate"], log_path)
        if code != 0:
            print("FAILED eval %s -- see %s; continuing" % (name, log_path))
            continue
        cmd_collect(zoo, name, run_dir)
        cmd_index(zoo)
        print("%s done in %.1f h" % (name, (time.time() - started) / 3600))


def main():
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("command", choices=["configs", "check", "train", "collect", "index"])
    ap.add_argument("args", nargs="*", help="method names (default: all in zoo.json); "
                                            "for collect: <method> <run_dir>")
    opt = ap.parse_args()
    os.chdir(config.REPO_ROOT)
    zoo = load_zoo()
    if opt.command == "configs":
        cmd_configs(zoo, opt.args)
    elif opt.command == "check":
        cmd_check(zoo, opt.args)
    elif opt.command == "train":
        cmd_train(zoo, opt.args)
    elif opt.command == "collect":
        if len(opt.args) != 2:
            raise SystemExit("collect needs <method> <run_dir>")
        cmd_collect(zoo, opt.args[0], opt.args[1])
        cmd_index(zoo)
    else:
        cmd_index(zoo)


if __name__ == "__main__":
    main()
